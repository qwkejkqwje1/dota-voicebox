// Ганк на миде: тревога для команды одной кнопкой
//
// Num1            — сирена в голосовой чат (и вам).
// Num1 два раза   — сирена + голос «Мид, ганк!».
// Ctrl+Num1       — голос «Мид пропал!» (враг ушёл с линии).
//
// Клавиши не отбираются у игры — Dota их тоже получит.
// Поменяйте под себя и нажмите «Сохранить» (Ctrl+S).

hotkey("Num1", () => {
  play("siren", { to: "team" });
});

combo("Num1 Num1", () => {
  say("Мид, ганк!", { to: "team" });
  notify("Тревога: ганк на миде");
}, { within: 400 }); // максимум мс между нажатиями

hotkey("Ctrl+Num1", () => {
  say("Мид пропал!", { to: "team" });
});
