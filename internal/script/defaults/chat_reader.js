// Чтение чата Dota 2 разными голосами (пример)
//
// Простое чтение чата включается на странице «Читалка» без скриптов. Этот пример — если хочется
// по-своему: союзников читает один голос, врагов — другой, свои сообщения и колесо чата пропускаются.
//
// on("chat", (m) => …) — новое сообщение в чате матча (нужен модуль Dota 2):
//   m.text — текст, m.channel — "all" (всем) | "team" (команде), m.player — номер игрока 0–9,
//   m.own — ваше сообщение, m.ally — союзник, m.wheel — фраза колеса чата, m.time — игровое время.
// read(text, { voice, to }) — прочитать голосом «Читалки» (фразы идут очередью, не перебивают друг друга):
//   voice — sly (ехидный), vile (мерзкий), demon, robot, chipmunk, grandpa, drunk, bass, alien,
//   radio, announcer, plain, live; to — "me" (только вы) | "team" (команда) | "both".

on("chat", (m) => {
  if (m.own || m.wheel) return; // своё и колесо чата не читаем
  if (m.text.length > 100) return; // простыни тоже
  const voice = m.ally ? "announcer" : "vile";
  read(m.text, { voice: voice, to: "me" }); // слышите только вы
});
