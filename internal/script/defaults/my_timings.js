// Мои тайминги: свои напоминания по игровому времени (пример)
//
// at("6:00", fn)               — один раз в 6:00
// at("6:00", fn, {before: 10}) — за 10 секунд до 6:00
// every("7:00", fn, {from: "7:00", until: "35:00", before: 15}) — повторять
// Игровое время берётся из Dota (GSI) и сглаживается между пакетами;
// без GSI можно нажать «Горн 0:00» на главной — отсчёт пойдёт вручную.

at("0:00", () => notify("Горн! Удачной игры"));

// лотосы каждые 3 минуты с 3:00, предупреждение за 10 секунд
every("3:00", (t) => {
  play("beep", { to: "me" });
  notify("Лотос в " + fmt(t));
}, { from: "3:00", until: "12:00", before: 10 });

// своё напоминание только себе
at("10:00", () => say("Проверь, пора ли собирать БКБ", { to: "me" }), { before: 5 });

// Торментор появляется в 20:00
at("20:00", () => say("Торментор через 30 секунд", { to: "team" }), { before: 30 });
